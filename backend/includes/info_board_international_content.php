<p>Curricular Practical Training (CPT) and Optional Practical Training (OPT) are F-1 practical-training categories for work directly related to study. They are not interchangeable. Eligibility, authorization agency, timing, employer requirements, and effects on later benefits differ.</p>

<h2>CPT</h2>
<p>CPT is an internship, cooperative education, work-study, or other training that is integral to an established curriculum. The DSO authorizes it for a specific employer, location, dates, and part- or full-time basis on Form I-20. No separate USCIS employment card is required, but work cannot begin before the authorization.</p>

<h2>OPT</h2>
<p>OPT is practical training directly related to the major and may be pre-completion or post-completion. The DSO recommends OPT in SEVIS, but the student applies to USCIS using Form I-765. Employment generally cannot begin until USCIS approves the application, the EAD is received, and the authorized start date arrives.</p>

<h2>Eligibility and timing</h2>
<p>Practical training generally requires one full academic year of lawful full-time enrollment, with limited exceptions and detailed study-abroad treatment. English-language training students are not eligible. Application windows and program-end dates are strict; plan with the DSO months ahead.</p>

<h2>How CPT affects OPT</h2>
<p>Twelve months or more of full-time CPT at the same educational level makes a student ineligible for OPT at that level. Part-time CPT does not trigger that bar. Pre-completion OPT generally reduces the amount remaining for post-completion OPT at the same level.</p>

<h2>STEM OPT</h2>
<p>Eligible graduates with a qualifying U.S. STEM degree may apply for a 24-month extension while in post-completion OPT. The employer must meet requirements including E-Verify participation and a training plan on Form I-983. Reporting, unemployment, supervision, and employer-change rules apply.</p>

<h2>Decision checklist</h2>
<p>Ask whether the experience is curricular, whether academic enrollment is required, who authorizes it, the earliest lawful start date, how it affects future OPT, and what must be reported. Get DSO confirmation for your record; do not rely on an employer’s immigration advice alone.</p>

