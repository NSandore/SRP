<p>Eligible F-1 students may generally work in qualifying on-campus employment up to 20 hours per week while school is in session and may have broader hours during authorized breaks. Location alone is not enough: an off-campus employer operating near campus is not automatically on-campus employment. Confirm eligibility with the DSO before starting.</p>

