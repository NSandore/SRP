        'Paid vs. Unpaid Internships' => <<<'HTML'
<p>A paid internship compensates work through wages or a stipend; an unpaid internship offers no wages. Academic credit and payment are separate questions. At a for-profit employer, calling someone an intern or awarding credit does not by itself remove wage obligations.</p>

<h2>Federal legal framework</h2>
<p>The U.S. Department of Labor explains that courts use a flexible “primary beneficiary” test to evaluate whether an intern at a for-profit employer is an employee entitled to minimum wage and overtime under the Fair Labor Standards Act. Factors include educational training, connection to formal education, accommodation of academics, limited duration, complementing rather than displacing paid work, and mutual understanding about compensation and future employment. No single factor decides every case.</p>

<h2>State and local law can add protection</h2>
<p>State or local wage rules may be more protective than federal law. Public-sector and nonprofit volunteering follows different principles and still requires careful classification. For an individual situation, contact the applicable labor agency or qualified counsel rather than relying on a forum.</p>

<h2>Calculate the true cost</h2>
<p>Include transportation, housing, meals, clothing, equipment, lost paid hours, and tuition or fees for internship credit. Ask about stipends, transit, housing, meal support, emergency grants, and campus internship funding. A valuable experience can still be financially impossible.</p>

<h2>Evaluate educational quality</h2>
<ul>
  <li>Written duties and learning goals.</li>
  <li>Named, available supervisor and regular feedback.</li>
  <li>Meaningful work with increasing responsibility.</li>
  <li>Reasonable duration and schedule.</li>
  <li>Safe, accessible environment and reporting process.</li>
  <li>No displacement of ordinary paid employees.</li>
</ul>

<h2>Questions before accepting</h2>
<p>Is the role paid, and how and when? Is the stipend treated as wages? Is academic credit required, and who pays the fee? What are the hours, location, supervision, insurance, confidentiality, and ownership terms? Get answers in writing.</p>

<h2>Red flags</h2>
<p>Beware of indefinite unpaid “trial” periods, commission-only work described as an internship, fees to participate, vague training, replacement of staff, personal errands unrelated to learning, or pressure to misclassify work. Never deposit a check and forward money.</p>

