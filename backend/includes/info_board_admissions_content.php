        'How to Compare College Offers' => <<<'HTML'
<p>A college offer is more than an acceptance letter. Compare the exact program and campus, the academic path, the support you are likely to use, and the amount you and your family must pay or borrow. Use the same categories and time period for every school.</p>

<h2>Start with the actual offer</h2>
<p>Confirm admission term, campus, major or pre-major, honors or special-program status, and conditions. A college with your major is not the same as direct admission to that major. Ask whether changing into or out of the program is possible and whether clinical, portfolio, or secondary admission gates exist.</p>

<h2>Calculate comparable net price</h2>
<p>For each school, total tuition, mandatory fees, housing and food, books and supplies, transportation, and realistic personal expenses. Subtract grants and scholarships that do not need repayment. Do not subtract loans or work-study as though they were discounts. This produces a more useful net-price estimate.</p>
<p>Separate first-year discounts from renewable aid. Record GPA, credit-load, residency, housing, major, participation, FAFSA, and deadline conditions. Model likely annual increases and at least four years for a bachelor’s path—or the realistic time for your program.</p>

<h2>Compare borrowing and risk</h2>
<p>List federal student loans, parent loans, private loans, and remaining payment gaps separately. Identify who is legally responsible, current interest and fees, whether a cosigner is needed, and when repayment begins. A gap is not solved merely because a lender may approve it.</p>

<h2>Compare academic fit and outcomes</h2>
<ul>
  <li>Required curriculum, course access, advising, class size, and faculty or lab opportunities.</li>
  <li>Accreditation and licensure outcomes for regulated professions.</li>
  <li>Retention, graduation, transfer, typical debt, and earnings data in context.</li>
  <li>Internship, co-op, research, study-away, and career support—including who actually gets access.</li>
  <li>Policies for changing majors, repeating courses, and transferring credit.</li>
</ul>

<h2>Compare daily life and support</h2>
<p>Consider housing guarantees and cost after year one, commute, transportation, food access, disability services, counseling and health care, tutoring, safety, campus climate, religious and cultural life, veteran or parenting support, and the ability to work. Visit if feasible or attend virtual sessions, and ask current students specific questions rather than “Do you like it?”</p>

