</ul>

<h2>Protect your admission</h2>
<p>Finish current classes and avoid assuming that admission makes grades irrelevant. Report material schedule, academic, conduct, or contact changes when the offer or college policy requires it. Do not ignore portal messages asking for verification. Keep copies of the offer, aid package, scholarship terms, deposit receipt, and correspondence.</p>

