<p>Review the academic calendar, move-in or commute plan, required technology, accessibility, emergency contacts, and transportation. Learn where advising, tutoring, counseling, health care, safety, Title IX, and basic-needs support are located. Build a first-term budget that includes books, course materials, travel, personal expenses, and timing differences between bills and aid disbursement.</p>

