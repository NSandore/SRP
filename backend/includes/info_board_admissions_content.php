<p>A strong application essay does not need a dramatic topic. Its job is to reveal something meaningful about how you think, what you notice, what shaped you, or how you act—using specific details that could not simply be copied into another applicant’s file.</p>

<h2>Answer the actual prompt</h2>
<p>Read the prompt, word limit, and college-specific instructions before drafting. Identify the question beneath the question: reflection, community, intellectual curiosity, challenge, contribution, or fit. A beautifully written piece that does not respond is still ineffective. For “Why us?” writing, connect particular academic or community opportunities to your goals; do not merely praise rankings, location, or prestige.</p>

<h2>Choose a focused story</h2>
<p>Small moments often work better than an entire life history. Start with a scene, decision, object, conversation, routine, or problem, then use it to show reflection. The event is evidence; your interpretation is the point. Avoid forcing trauma into the essay or disclosing private information you do not want shared. You never owe a college your most painful experience.</p>

<h2>Draft in your own voice</h2>
<p>Write plainly enough that the reader can follow you in one pass. Specific nouns and actions are stronger than claims such as “I am passionate” or “this taught me leadership.” Show what changed, what remains complicated, or what you would do next. Humor can work when it is natural and not at another person’s expense.</p>

<h2>Revise for meaning before grammar</h2>
<ol>
  <li>Write a complete draft without trying to perfect the opening.</li>
  <li>Underline the sentences that reveal insight; remove background that overwhelms them.</li>
  <li>Check that the ending adds understanding rather than repeats the introduction.</li>
  <li>Read aloud for rhythm, missing words, and sentences that sound unlike you.</li>
  <li>Ask one or two trusted readers what they learned about you—not what they would write instead.</li>
  <li>Proofread inside the final application preview, including formatting and word count.</li>
</ol>

