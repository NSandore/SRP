<p>A deferral commonly moves an Early Action or Early Decision application into Regular Decision review. You normally do not submit a new application. The college may request midyear grades or allow a concise letter of continued interest. Send only what is permitted, and do not interpret a deferral as a promise or a rejection.</p>

