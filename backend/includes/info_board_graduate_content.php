        'Graduate School Funding Basics' => <<<'HTML'
<p>Graduate funding can combine fellowships, scholarships, assistantships, employer support, savings, and loans. Admission does not guarantee funding, and “funded” does not always cover fees, insurance, summer, dependents, or the local cost of living.</p>

<h2>Gift and service-based funding</h2>
<p>Fellowships and scholarships generally do not require repayment, though they can carry enrollment, research, service, or tax conditions. Assistantships exchange teaching, research, or administrative work for a stipend and possibly tuition remission and insurance.</p>

<h2>Read every offer line</h2>
<p>Identify annual stipend, months covered, tuition waiver amount, mandatory fees, insurance premium, workload, appointment percentage, renewal conditions, maximum years, summer support, and taxes. Ask whether funding follows the student or depends on a specific grant or advisor.</p>

<h2>Current federal loan changes</h2>
<p>Beginning July 1, 2026, most new graduate and professional borrowers are no longer eligible for Grad PLUS, subject to a limited transition exception for qualifying continuing students. New annual, aggregate, and lifetime limits apply, and institutions may set consistently applied lower program limits. Obtain an individual determination from financial aid.</p>

<h2>Compare net cost through completion</h2>
<p>Include fees, living expenses, relocation, equipment, conference travel, licensing, family costs, and realistic time to degree. Subtract guaranteed funding only. Model borrowing and interest under current rules; do not count hoped-for assistantships.</p>

<h2>External and employer support</h2>
<p>Search federal agencies, foundations, professional associations, research councils, employers, and home-country sponsors. Check portability, service commitments, intellectual-property terms, and interaction with institutional funding.</p>

<h2>Warning signs</h2>
<p>Be cautious when funding is verbal, depends on unspecified future grants, omits fees, requires excessive work, or is guaranteed for less time than typical completion. Ask current students whether stipends arrive on time and cover local necessities. Recalculate the package if tuition, fees, appointment duties, or expected completion time changes.</p>

