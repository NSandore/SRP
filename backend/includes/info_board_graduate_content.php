<p>A graduate assistantship is a work appointment connected to enrollment. Common forms include teaching assistantships, research assistantships, and administrative or graduate assistantships. Compensation can include a stipend or wage, tuition remission, insurance, and fee support, but packages vary widely.</p>

<h2>Common responsibilities</h2>
<p>Teaching assistants may lead sections, grade, hold office hours, or teach courses. Research assistants work on funded projects and may contribute to a thesis or dissertation. Administrative assistants support programs, labs, services, or events. Ask for actual duties rather than relying on the title.</p>

<h2>Read the appointment</h2>
<p>Confirm start and end dates, weekly or percentage effort, supervisor, pay schedule, tuition covered, excluded fees, insurance, vacation, sick leave, union coverage, training, evaluation, renewal, and termination. Learn whether summer requires a separate appointment.</p>

<h2>Academic relationship</h2>
<p>Research work may overlap the student’s scholarship or dissertation, creating questions about authorship, data ownership, advisor power, and progress. Teaching can build valuable experience but consume time. Ask how workload is monitored and conflicts are resolved.</p>

<h2>Taxes and benefits</h2>
<p>Stipends, wages, tuition benefits, and fellowships can receive different tax treatment. The institution may withhold some taxes without resolving the student’s full liability. International students should use status-aware tax resources and confirm employment authorization.</p>

<h2>Compare offers</h2>
<p>Calculate net pay after fees, insurance, taxes, and local living costs. Compare guaranteed years, summer coverage, expected completion time, duties, mentoring, and backup funding. A larger stipend in a high-cost location may provide less usable support.</p>

