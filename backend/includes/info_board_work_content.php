<p>Federal Work-Study (FWS) provides part-time employment for eligible students with financial need at participating schools. An FWS amount on an aid offer is an earnings opportunity—not a grant, an automatic tuition credit, or a guaranteed job.</p>

<h2>Confirm the award and process</h2>
<p>Complete the FAFSA and follow the school’s instructions. Ask whether the award must be accepted, whether jobs are competitive, when hiring opens, and whether returning students receive priority. Eligibility and funding can change by award year, so a prior job does not guarantee the next one.</p>

<h2>Search and apply</h2>
<p>Approved jobs may be on campus or with eligible off-campus nonprofit, public, community-service, or private-sector employers. Use the school’s authorized listing and confirm that the specific position can use FWS. Apply as for any job with a targeted resume, availability, and interview preparation.</p>

<h2>Understand pay and the award limit</h2>
<p>Undergraduates must be paid hourly; graduate students may be hourly or salaried. Pay must meet applicable wage law and should relate to duties and skills. Students receive paychecks for hours actually worked. The award limits total FWS earnings, not the hourly wage, and the school may set permitted hours to avoid exceeding it.</p>

<h2>Plan the schedule</h2>
<p>The school and employer should consider class schedule, academic progress, financial need, wage, and employment period. Ask how to track remaining eligibility and what happens when funds run out. Do not work unreported hours or assume the employer can move excess hours to another pay period.</p>

<h2>Know the aid and tax treatment</h2>
<p>FWS earnings are generally taxable wages and may require a federal or state return. They receive special treatment in the federal aid calculation and ordinarily are excluded from income used to determine the next aid offer. Keep W-2 forms and identify the earnings correctly when aid forms request them.</p>

<h2>Use the experience</h2>
<p>Choose duties that build useful skills when possible, then record projects, tools, outcomes, and supervisor feedback. If the job is not career-related, customer service, reliability, records, teamwork, and problem-solving remain transferable. Ask about regular payroll, another approved job, or next-year reapplication before the award ends.</p>

