<p>An on-campus job is employment for the college or for an eligible operation located on campus. It may be funded by the employer’s regular payroll or by Federal Work-Study. “On campus” describes location or relationship; it does not guarantee a work-study award, academic credit, flexible hours, or a particular wage.</p>

<h2>Common roles</h2>
<p>Students may work in libraries, laboratories, offices, recreation, residence life, dining, events, tutoring, technology, admissions, facilities, or peer programs. Some roles build field-specific experience; others develop reliable service, teamwork, communication, safety, and administrative skills.</p>

<h2>Regular payroll versus Work-Study</h2>
<p>A regular student employee is paid from an employer budget. A Federal Work-Study employee must have an eligible award and obtain an approved position, and earnings are limited by that award. Both are jobs: students are paid for hours worked, usually through payroll, rather than receiving the full amount automatically against tuition.</p>

<h2>Finding and evaluating openings</h2>
<p>Check the school’s employment portal, career center, financial aid office, departments, and approved vendors. Ask about duties, supervisor, hourly rate, maximum hours, shift stability, training, breaks, required holidays, summer work, background checks, and whether employment ends when enrollment changes.</p>

<h2>Pay and workplace protections</h2>
<p>Most students doing ordinary compensated campus work are employees and are generally covered by applicable wage, hour, safety, and nondiscrimination rules. Some educational relationships—such as certain research, teaching, or resident-assistant arrangements—can be treated differently. Record hours accurately, review pay statements, and use HR or the appropriate labor agency for unresolved wage questions.</p>

<h2>Taxes, aid, and benefits</h2>
<p>Campus wages are generally taxable income even when earned through Work-Study, though qualifying student employment can receive special Social Security and Medicare treatment. Work-Study earnings receive special treatment in the federal aid calculation. A job may not include employee benefits; read the appointment rather than assuming.</p>

