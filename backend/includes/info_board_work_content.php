<p>Ask about minimum hours, shift-posting dates, schedule changes, mandatory overtime, busy seasons, remote expectations, and commute. A slightly lower-paying job with consistent shifts can be more sustainable than higher pay with last-minute scheduling. On-campus work may reduce travel, but it is not automatically flexible.</p>

<h2>Protect academic essentials</h2>
<p>Put exams, required attendance, registration, and major deadlines on one calendar. Use shorter study blocks between commitments and reserve longer blocks for demanding work. Tell instructors early when a real emergency occurs, but do not assume employment excuses course requirements.</p>

<h2>Communicate before conflicts</h2>
<p>Give an employer your availability before the schedule is posted and update it when classes change. Ask for a specific arrangement rather than “more flexibility.” Confirm approved changes in writing. Academic convenience alone does not generally create a federal right to a preferred shift, although a protected disability, pregnancy-related limitation, or religious practice may involve a separate accommodation process.</p>

<h2>Watch money and aid</h2>
<p>Compare net earnings after tax, transportation, meals, clothing, and childcare. Ask financial aid how employment, enrollment changes, or dropping a course could affect the current or future aid package. Federal Work-Study has its own award and hour controls.</p>

