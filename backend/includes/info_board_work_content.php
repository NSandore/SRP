        'Taxes for College Students: The Basics' => <<<'HTML'
<p>Being a student does not by itself remove a tax-filing obligation. Filing depends on income type and amount, dependency, filing status, residency for tax purposes, and other circumstances. Federal, state, and sometimes local returns use different rules.</p>

<h2>Identify how you were paid</h2>
<p>Employees generally receive Form W-2 and have payroll taxes withheld. Independent contractors and gig workers may receive Forms 1099, but income is reportable even when no form arrives. Net self-employment earnings of $400 or more generally trigger a federal return and self-employment tax; estimated payments may also apply.</p>

<h2>Determine whether to file</h2>
<p>Use the current IRS filing-requirement tool or Publication 501 rather than an old income threshold. Dependents have special rules, especially for unearned income. Filing can still be worthwhile when it is not required if federal or state tax was withheld and a refund may be due.</p>

<h2>Understand scholarships and education benefits</h2>
<p>A qualified scholarship used for required tuition, fees, books, supplies, and equipment can be tax-free when the requirements are met. Amounts used for room, board, travel, optional equipment, or payment for services can be taxable. Assistantships, stipends, and tuition benefits require fact-specific treatment.</p>

<h2>Coordinate education credits</h2>
<p>The American Opportunity Tax Credit and Lifetime Learning Credit have different student, expense, year, and income rules. The same expense cannot support multiple tax benefits. If another taxpayer claims the student as a dependent, that taxpayer is generally the one who may claim an education credit. Use Form 1098-T as a starting record, not proof that every amount qualifies.</p>

<h2>Keep records and check withholding</h2>
<p>Save W-2s, 1099s, Form 1098-T, scholarship terms, billing statements, receipts, and prior returns. Review the first pay statement and use the IRS withholding estimator when circumstances change. File every required state return, including for work or residence in more than one state.</p>

<h2>Get appropriate help</h2>
<p>IRS Free File and VITA offer free options for eligible taxpayers. International students may be nonresident aliens for tax purposes and can have different forms, treaty rules, and filing software; use the school’s international tax resources or qualified help. Never post Social Security numbers, tax forms, or identity documents in a forum.</p>

