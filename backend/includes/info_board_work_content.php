        'How to Ask Your Employer for a School-Friendly Schedule' => <<<'HTML'
<p>A useful schedule request is early, specific, and realistic about the job’s needs. School attendance alone does not generally guarantee a preferred shift under federal law, but many employers will consider a workable proposal—especially when availability is clear before schedules are built.</p>

<h2>Prepare the request</h2>
<p>List required class times, commute, recurring academic commitments, and the shifts you can reliably work. Identify the smallest change needed and two alternatives. Review availability, scheduling, union, leave, and shift-swap policies before speaking with the supervisor.</p>

<h2>Ask at the right time</h2>
<p>Raise known conflicts before accepting a job, when registering for a new term, or before the schedule deadline. For an unexpected exam or required event, ask as soon as it is announced. Last-minute requests are harder to solve and can shift burdens to coworkers.</p>

<h2>Use a concrete script</h2>
<p>Try: “My required class meets Tuesdays and Thursdays from 2 to 4. Beginning August 25, I can reliably work Monday, Wednesday, and Friday after noon and weekends. Could we remove those two class-time shifts? I can take the Friday closing shift or discuss another coverage plan.” Do not promise availability you cannot sustain.</p>

<h2>Offer workable options</h2>
<p>Possible solutions include consistent availability blocks, swapping shifts through the approved process, earlier or later shifts, fewer hours during exams, compressed hours, remote duties, or a temporary change. Confirm who arranges coverage and never work off the clock to compensate.</p>

<h2>Document the result</h2>
<p>Send a short follow-up stating the approved availability, start date, and review date. Keep schedules and time records. If the request is denied, ask what constraint prevents it and whether another role or shift is available. Decide whether the job remains compatible rather than repeatedly missing work or class.</p>

<h2>Separate accommodations from ordinary requests</h2>
<p>A schedule change related to disability, pregnancy, childbirth, or sincerely held religious practice may involve legal protections and a formal interactive process, depending on the facts and employer. State law may add rights. Contact HR or the designated accommodation office and describe the work-related change needed; private medical details need not be shared with classmates or supervisors beyond the proper process.</p>

