<p>Before the term, decide what changes first if capacity fails: overtime, optional commitments, course load, or timeline. Learn add/drop, withdrawal, refund, incomplete, leave, and satisfactory-progress rules. Contact the instructor, advisor, financial aid office, and employer before a manageable problem becomes an avoidable failure.</p>

