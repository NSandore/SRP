  <li>Respect financial, disability, family, citizenship, and health constraints.</li>
</ul>

<h2>How to get a useful answer</h2>
<p>Ask one focused question and identify what the school or employer has already confirmed. Separate facts in a written policy from personal practice. If advice conflicts, pause before changing enrollment, accepting unpaid work, signing repayment terms, or beginning employment that may require authorization.</p>

<h2>Before making a change</h2>
<p>Check the weekly time budget, net pay, job terms, course requirements, add/drop or withdrawal deadline, aid and loan effects, insurance, benefits, and immigration status. Keep written approvals and protect private information.</p>

