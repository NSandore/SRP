        'Working Full-Time While Attending School' => <<<'HTML'
<p>Working full-time while enrolled can be necessary and achievable, but it leaves little margin for unpredictable courses, overtime, illness, and caregiving. Build the degree around sustainable capacity and verified program rules rather than assuming a standard full-time course schedule will fit.</p>

<h2>Choose the academic format carefully</h2>
<p>Compare part-time, evening, weekend, online, hybrid, and accelerated options. Verify live meeting times, exams, group work, laboratories, clinicals, internships, campus visits, and course rotation. “Asynchronous” does not mean self-paced or free of deadlines.</p>

<h2>Build a term-by-term plan</h2>
<p>Map prerequisites and courses offered only once a year. Start with a load that fits the job’s busiest season and adjust after real results. A lighter term can protect progress better than repeatedly withdrawing, but it may extend completion or change tuition and aid.</p>

<h2>Clarify work expectations</h2>
<p>Review ordinary hours, overtime, on-call duties, travel, remote availability, busy periods, and schedule notice. Ask about predictable shifts, tuition assistance, education leave, compressed schedules, or temporary flexibility. Obtain approvals before registration when the class depends on them.</p>

<h2>Plan the full cost</h2>
<p>Include tuition, fees, books, technology, commuting, childcare, reduced overtime, and emergency reserves. Complete required aid steps and disclose employer benefits when requested. Changing below half-time or withdrawing can affect aid, loan status, insurance, and other benefits.</p>

<h2>Protect performance and health</h2>
<p>Reserve fixed study periods and sleep, use office hours and tutoring early, and tell household members what the schedule requires. Watch for unsafe fatigue, repeated missed work or class, academic decline, and worsening health. Use formal accommodation, leave, or employee-assistance processes when applicable.</p>

