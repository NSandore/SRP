<p>Repeated missed classes, late work, unsafe fatigue, declining grades, skipped medical care, or borrowing simply to support job costs are signs to revisit the plan. Options include fewer shifts, a different job, a lighter course load, a leave process, emergency aid, or a new graduation timeline. Check academic, billing, aid, insurance, and immigration effects before changing enrollment.</p>

