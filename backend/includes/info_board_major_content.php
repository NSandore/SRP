<h2>Start with the actual curriculum</h2>
<p>Read the catalog requirements rather than choosing from the major’s name. Review introductory and advanced courses, prerequisites, required grades, labs, studios, clinicals, fieldwork, capstone, and separate program admission. Ask which courses are offered only once a year and whether the program is accredited when licensure or certification may matter.</p>

<h2>Separate interests, skills, and work values</h2>
