        'Major vs. Minor vs. Concentration' => <<<'HTML'
<p>A major, minor, and concentration all organize coursework, but they do different jobs. The labels are not nationally standardized, so the catalog—not the name—determines credits, requirements, transcript notation, and whether the option is available with your degree.</p>

<h2>Major</h2>
<p>The major is the primary organized field within a degree. It usually includes introductory, methods, advanced, and capstone requirements plus minimum grades or GPA. Some degrees require one major; others use a broader program name. Admission to the major can be separate from admission to the institution.</p>

<h2>Minor</h2>
<p>A minor is a smaller secondary field completed alongside a degree. It usually appears on the transcript rather than as a separate degree. It may complement the major, build a skill, or support an interest, but it does not normally establish professional licensure and may be removed if unfinished at graduation.</p>

<h2>Concentration and related labels</h2>
<p>A concentration, emphasis, option, specialization, or track is commonly a focused pathway inside a major or degree. It may guide electives or create a prescribed sequence. Some institutions record it on the transcript or diploma; others use it only for advising. The same word can mean different things across schools.</p>

<h2>How requirements overlap</h2>
<p>Colleges may limit how many courses can count for both a major and minor, between two majors, or among concentrations. A course can satisfy two requirement categories while still contributing its credits only once to the degree total. Minimum upper-level and institutional-residency credits may apply separately.</p>

<h2>How employers and graduate schools use them</h2>
<p>Readers may notice the label, but they often care more about relevant coursework, skills, experience, portfolio, research, and performance. A concentration or minor is not a substitute for a required accredited program, license, certification, or prerequisite set. List the credential accurately and do not imply a second degree.</p>

<h2>Questions to ask</h2>
<ul>
  <li>How many new credits and terms does this add?</li>
  <li>Which courses can overlap, and what minimum grades apply?</li>
  <li>Will it appear on the transcript or diploma?</li>
