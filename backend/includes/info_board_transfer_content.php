        'What Is an Articulation Agreement?' => <<<'HTML'
<p>An articulation agreement is a written arrangement describing how specified courses, credits, credentials, or program requirements move between institutions. It can make transfer more predictable, but it is not a universal promise that every credit will apply to every degree.</p>

<h2>Common types of agreements</h2>
<ul>
  <li><strong>Course-to-course:</strong> identifies one sending course as equivalent to a receiving course.</li>
  <li><strong>General-education block:</strong> treats an approved set of courses or completed credential as satisfying a group of requirements.</li>
  <li><strong>Program-to-program or degree pathway:</strong> maps an associate program into a specific bachelor’s major.</li>
  <li><strong>Guaranteed admission:</strong> promises university admission when stated conditions are met, often without guaranteeing a particular major.</li>
  <li><strong>Dual-admission or co-enrollment:</strong> coordinates advising or enrollment across partner institutions.</li>
  <li><strong>Statewide agreement:</strong> establishes common rules across a public system or participating institutions.</li>
</ul>

<h2>What to read in the agreement</h2>
<p>Identify the sending and receiving institutions, eligible campuses and majors, required degree, course map, minimum course grades and GPA, application and completion deadlines, catalog year, residency requirement, maximum credits, and effective dates. Check exclusions for competitive majors, online divisions, technical courses, or discontinued programs.</p>

<h2>What an agreement may not guarantee</h2>
<p>University admission may not include admission to nursing, engineering, business, education, or another selective program. The agreement may not guarantee financial aid, housing, junior standing, completion in two years, or transfer to a third institution. It may protect a completed general-education block but not every major prerequisite.</p>

<h2>Keep the agreement active</h2>
<p>Curricula and partnerships change. Save the version that applies to your entry and completion dates, but confirm whether the agreement provides catalog-year protection. Meet with advisors at both institutions after any change in major, attendance break, repeated course, or missed deadline. Do not substitute a “similar” course without written approval.</p>

<h2>Agreement versus equivalency database</h2>
<p>An equivalency database records how individual courses have been evaluated, while an articulation agreement coordinates a broader pathway and its conditions. Both are planning tools. A database entry can change, and a course that transfers generally may still be wrong for a particular degree.</p>

<h2>If the agreement is not followed</h2>
<ol>
  <li>Compare your record with the exact agreement and effective dates.</li>
  <li>Ask the transfer-credit office to identify the unmet condition or policy.</li>
  <li>Provide the agreement, transcript, degree award, and written advising records.</li>
  <li>Use the institution’s transfer-credit or academic appeal process.</li>
  <li>Escalate through the state or system process only when the agreement identifies one.</li>
</ol>

<h2>Planning questions</h2>
<p>Does the agreement cover my major and campus? Must I complete the associate degree before transfer? Which grades count? Is admission guaranteed to the institution or program? Which credits remain after transfer? What happens if the agreement expires while I am enrolled? Get the answers in writing.</p>

