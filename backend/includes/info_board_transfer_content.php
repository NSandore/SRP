        'How Transfer Credits Work' => <<<'HTML'
<p>Transfer credit is academic credit a receiving institution awards for learning completed elsewhere. The receiving college—not the sending college, course provider, or transfer website—makes the final decision. A course can transfer as an exact equivalent, subject elective, general elective, block of credit, or not at all.</p>

<h2>Acceptance is not the same as degree application</h2>
<p>Credit moves through several decisions:</p>
<ol>
  <li><strong>Source review:</strong> Is the prior institution and coursework eligible for consideration?</li>
  <li><strong>Credit award:</strong> Will the receiving school award credit, and how many semester or quarter credits?</li>
  <li><strong>Equivalency:</strong> Does it match a specific local course or only an elective area?</li>
  <li><strong>Degree application:</strong> Does it satisfy general education, major, minor, prerequisite, upper-level, or elective requirements?</li>
</ol>
<p>A transcript can show 60 accepted credits while the degree audit applies fewer than 60 to the selected program.</p>

<h2>What evaluators commonly examine</h2>
<ul>
  <li>Institutional accreditation or other recognition accepted under policy.</li>
  <li>Course level, content, learning outcomes, contact or credit hours, and grade.</li>
  <li>Whether the course is college-level, technical, developmental, graduate, or continuing education.</li>
  <li>Age of coursework where fields change rapidly or licensure rules impose limits.</li>
  <li>Fit with the receiving curriculum and the student’s catalog year and major.</li>
</ul>
<p>Accreditation does not guarantee transfer, and lack of a prelisted equivalency does not necessarily mean denial. It may mean the course needs faculty review.</p>

<h2>Grades, GPA, and repeats</h2>
<p>Many institutions require a minimum grade for transfer, with higher grades for major prerequisites. Accepted transfer grades often do not enter the new institution’s institutional GPA, but they can still matter for admission, honors, satisfactory academic progress, graduate applications, licensure, and programs that calculate an all-college GPA. Repeat and forgiveness rules rarely erase the original course from every purpose.</p>

<h2>Credit limits and residency</h2>
<p>A college may limit credits from two-year institutions, apply different limits to upper-division work, or cap exam and prior-learning credit. It will also require a minimum amount of the degree—sometimes including the final credits or major courses—to be completed through that institution. This is called an institutional or residency requirement and usually refers to where credit is earned, not where you live.</p>

<h2>Semester and quarter conversion</h2>
<p>Quarter and semester credits are not one-for-one. The receiving school applies its own conversion and rounding rules. A converted course can carry fewer credits than the local requirement even when the subject matches, creating a partial-credit shortage that needs department review or another course.</p>

<h2>How to improve the result</h2>
<p>Send official transcripts from every institution and gather syllabi for courses without established equivalencies. Preserve catalog descriptions from the term you took each course. If a decision seems wrong, use the published appeal process and explain the specific equivalency or degree requirement you are requesting. A verbal promise from a recruiter or advisor should be confirmed in writing by the office authorized to award credit.</p>

