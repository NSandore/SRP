        'How to Read a Transfer Credit Evaluation' => <<<'HTML'
<p>A transfer credit evaluation lists how the receiving institution treated prior coursework. It is not always the same as a degree audit. The evaluation answers what credit was awarded; the degree audit shows how that credit applies to your selected program and what remains.</p>

<h2>Find the document’s scope</h2>
<p>Confirm which transcripts, institutions, terms, and in-progress courses were reviewed. Look for notes such as preliminary, unofficial, pending final transcript, or subject to department review. An evaluation completed for one major or catalog year may change if you switch programs.</p>

<h2>Understand common outcomes</h2>
<ul>
  <li><strong>Direct equivalent:</strong> the prior course matches a named local course.</li>
  <li><strong>Subject elective:</strong> credit is accepted in a department but not matched to a particular course.</li>
  <li><strong>General elective:</strong> credit counts toward the overall total but may not satisfy a specific requirement.</li>
  <li><strong>General-education attribute:</strong> the course satisfies a distribution area, sometimes in addition to an equivalency.</li>
  <li><strong>Duplicate:</strong> the learning overlaps another transferred or completed course and cannot earn credit twice.</li>
  <li><strong>No credit or denied:</strong> the course did not meet policy or documentation requirements.</li>
  <li><strong>Pending:</strong> a syllabus, final grade, credential evaluation, or faculty decision is still required.</li>
</ul>

<h2>Check credits and conversions</h2>
<p>Compare attempted credits with accepted credits. Quarter-to-semester conversion can produce decimals or a shortfall against a local course. Laboratory and lecture components may transfer separately. Verify whether the receiving school granted the correct level—lower division, upper division, undergraduate, or graduate.</p>

<h2>Compare with the degree audit</h2>
<p>For each accepted course, identify whether it fills general education, the major, a prerequisite, a minor, or only elective space. Look for unused or “fall-through” credit and requirements still marked incomplete. Confirm minimum-grade rules; a course can transfer as credit but fail to satisfy a major requirement that demands a higher grade.</p>

<h2>Review institutional limits</h2>
<p>Find the maximum transferable credit, limits by source or level, and the residency requirement. Some credits may be accepted but excluded because the degree has reached an elective cap. Also check requirements for upper-level work, the final credits, capstones, clinicals, and courses that must be completed in the department.</p>

<h2>Correct missing or unexpected decisions</h2>
<ol>
  <li>Verify that the official transcript and final grade arrived.</li>
  <li>Read the published transfer-credit and appeal policy.</li>
  <li>Gather the syllabus and catalog description from the exact term.</li>
  <li>Request a specific equivalency or degree application and explain the match.</li>
  <li>Meet the appeal deadline and keep the written ruling.</li>
  <li>Confirm that both the transcript and degree audit update afterward.</li>
</ol>

<h2>Questions to ask an advisor</h2>
<p>Which accepted credits do not advance my program? Which prerequisites remain? Are any evaluations pending? How many terms are realistically left based on course sequencing? What happens if I change majors? Ask the registrar or transfer-credit office about the award of credit and the academic department about its application to specialized requirements.</p>

