const LanguageContext = createContext(null);

const readInitialLanguage = () => {
  if (typeof window === 'undefined') return 'en';
  try {
    const savedLanguage = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    return SUPPORTED_LANGUAGES.has(savedLanguage) ? savedLanguage : 'en';
  } catch (error) {
    return 'en';
  }
};

const getNestedValue = (source, path) =>
  path.split('.').reduce((value, segment) => value?.[segment], source);

const interpolate = (template, values) =>
  String(template).replace(/\{\{(\w+)\}\}/g, (match, key) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match
  );

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(readInitialLanguage);

  const setLanguage = useCallback((nextLanguage) => {
    if (SUPPORTED_LANGUAGES.has(nextLanguage)) {
      setLanguageState(nextLanguage);
    }
  }, []);

  const t = useCallback((key, values = {}) => {
    const translated = getNestedValue(translations[language], key);
    const fallback = getNestedValue(translations.en, key);
    return interpolate(translated ?? fallback ?? key, values);
  }, [language]);

  useEffect(() => {
    const activeLanguage = LANGUAGE_OPTIONS.find((option) => option.value === language);
    document.documentElement.lang = language;
    document.documentElement.dir = activeLanguage?.direction || 'ltr';
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
    } catch (error) {
      // The language still works for this session when storage is unavailable.
    }
  }, [language]);

  const value = useMemo(() => ({
    language,
    locale: LANGUAGE_OPTIONS.find((option) => option.value === language)?.locale || 'en-US',
    setLanguage,
    t,
  }), [language, setLanguage, t]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
